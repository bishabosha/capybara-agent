package capybara.agent

/** The manifest is the bridge from trusted factories to explicit safe parameters. */
object SkillScaffold:
  def bindings(builtins: Skill, skill: Skill): Seq[SkillBinding] =
    val all = builtins.bindings ++ (
      if skill.requiresRuntimeClasspath && skill.universe != builtins.universe then skill.bindings
      else Nil
    )
    require(all.map(_.name).distinct.size == all.size, "Duplicate capability parameter names in manifests")
    for binding <- all do
      require(binding.name.matches("[a-zA-Z_][a-zA-Z0-9_]*"), s"Invalid capability name: ${binding.name}")
      require(binding.tpe.nonEmpty && binding.value.nonEmpty, s"Incomplete capability binding: ${binding.name}")
    require(builtins.bindings.exists(_.name == "output"), "Builtins must provide the output capability")
    all

  def definition(name: String, bindings: Seq[SkillBinding], code: String): String =
    val parameters = bindings.map(b => s"${b.name}: ${b.tpe}").mkString("(using ", ", ", ")")
    s"""def $name$parameters: Unit = {
       |$code
       |()
       |}
       |""".stripMargin

  def invocation(name: String, bindings: Seq[SkillBinding]): String =
    def local(binding: SkillBinding): String = s"__capybara_${binding.name}"
    val values = bindings.map(b => s"val ${local(b)}: ${b.tpe} = ${b.value}").mkString("\n")
    val arguments = bindings.map(local).mkString("(using ", ", ", ")")
    s"""{
       |$values
       |try { $name$arguments; true }
       |catch {
       |  case scala.util.control.NonFatal(error) =>
       |    __capybara_output.printErr(builtins.baseReflectiveShowable(error))
       |    false
       |}
       |}
       |""".stripMargin

  def entryPoint(name: String, snippet: String, bindings: Seq[SkillBinding]): String =
    s"""def $name(__harnessStdout: java.io.PrintStream, __harnessStderr: java.io.PrintStream): Boolean =
       |${invocation(snippet, bindings)}
       |""".stripMargin

  /** Readable version of exactly the same parameter/factory wiring used by the REPL. */
  def preview(builtins: Skill, skill: Skill): String =
    val all = bindings(builtins, skill)
    val imports = (builtins.predef.toSeq ++ (
      if skill.requiresRuntimeClasspath && skill.universe != builtins.universe then skill.predef.toSeq
      else Nil
    )).mkString("\n")
    s"""// Generated by skill-ide. Edit the original skill sources, not this preview.
       |object SkillPreview {
       |$imports
       |// ReplExec compiles this method separately under safe mode.
       |${definition("snippet", all, "// Your snippet runs here, with explicitly supplied capabilities.")}
       |// This caller is trusted harness code; factories are rejected in safe mode.
       |${entryPoint("run", "snippet", all)}
       |}
       |""".stripMargin
